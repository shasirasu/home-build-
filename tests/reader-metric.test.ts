import { describe, expect, it, beforeAll } from 'vitest';
import fs from 'node:fs';
import * as pdfjs from 'pdfjs-dist/legacy/build/pdf.mjs';
import { extractPrims } from '@/lib/reader/extract';
import { readPlan, type ReadResult } from '@/lib/reader/readPlan';
import { specFromPlan } from '@/lib/reader/buildSpec';
import { deriveSpec } from '@/lib/derive';
import { autoFurnish } from '@/lib/furnish';
import type { HouseSpec } from '@/types/house';

// A second plan, unlike the sample on purpose: one floor, millimetres, 1:50, windows drawn, a blue dimension line,
// no columns and no stair. Generated by scratch script make_metric_plan.py (PyMuPDF); see tests/fixtures.

let res: ReadResult;
let spec: HouseSpec;

beforeAll(async () => {
  const data = new Uint8Array(fs.readFileSync('tests/fixtures/metric-plan.pdf'));
  const doc = await pdfjs.getDocument({ data, useSystemFonts: true, verbosity: 0 }).promise;
  res = readPlan(await extractPrims((await doc.getPage(1)) as never, pdfjs.OPS as never));
  spec = res.ok ? deriveSpec(specFromPlan(res, 'Metric', { kind: 'pdf', page: 1 })) : (null as never);
});

describe('plan reader on a metric single-floor plan', () => {
  it('reads the scale from a millimetre dimension', () => {
    expect(res.ok, res.reason).toBe(true);
    expect(res.imperial).toBe(false);
    expect(res.scaleText).toBe('9000');
    expect(res.unitsPerMetre).toBeCloseTo((72 / 25.4 / 50) * 1000, 0);
    expect(res.floors.length).toBe(1);
    expect(res.floors[0].width).toBeCloseTo(9, 1);
    expect(res.floors[0].depth).toBeCloseTo(7, 1);
  });

  it('finds the five walls, the two doors and the drawn window', () => {
    const lv = spec.levels[0];
    expect(lv.walls.length).toBe(5);
    expect(lv.walls.filter((w) => w.kind === 'exterior').length).toBe(4);
    expect(lv.walls.find((w) => w.kind !== 'exterior')!.thickness).toBeCloseTo(0.115, 2);
    const doors = lv.openings.filter((o) => o.kind === 'door');
    expect(doors.length).toBe(2);
    const entrance = doors.find((d) => d.style === 'teak-panel')!;
    expect(entrance.name).toBe('Entrance');
    expect(entrance.width).toBeCloseTo(1.1, 1);
    const inner = doors.find((d) => d.style === 'flush')!;
    expect(inner.width).toBeCloseTo(0.9, 1);
    expect(inner.hinge).toBe('b'); // lower jamb, as drawn
    expect(inner.swing).toBe(1); // into the left-hand room
    const windows = lv.openings.filter((o) => o.kind === 'window');
    expect(windows.length).toBe(1);
    expect(windows[0].assumed).toBeFalsy();
    expect(windows[0].width).toBeCloseTo(1.5, 1);
  });

  it('reads both rooms with their metric sizes', () => {
    const rooms = spec.levels[0].rooms;
    expect(rooms.map((r) => r.name).sort()).toEqual(['Bedroom', 'Living']);
    const living = rooms.find((r) => r.name === 'Living')!, xs = living.polygon.map((p) => p[0]), ys = living.polygon.map((p) => p[1]);
    expect(Math.max(...xs) - Math.min(...xs)).toBeCloseTo(4.27, 1);
    expect(Math.max(...ys) - Math.min(...ys)).toBeCloseTo(6.54, 1);
    expect(living.type).toBe('living');
  });

  it('gets a generated frame and furniture', () => {
    expect(spec.structure.fromPlan).toBeFalsy();
    expect(spec.structure.columns.length).toBeGreaterThanOrEqual(4);
    expect(spec.roof.outline.length).toBe(4);
    const kinds = autoFurnish(spec).map((i) => i.kind);
    expect(kinds.some((k) => k.startsWith('bed-'))).toBe(true);
    expect(kinds.some((k) => k.startsWith('sofa'))).toBe(true);
  });
});

describe('files the reader cannot use say why', () => {
  it('a page with no linework (a scan or photo)', () => {
    const r = readPlan({ width: 800, height: 600, segs: [], loops: [], curves: [], texts: [] });
    expect(r.ok).toBe(false);
    expect(r.reason).toMatch(/scan or a photo/);
  });
});
